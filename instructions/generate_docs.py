from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor


def new_doc() -> Document:
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(12)
    style.paragraph_format.space_after = Pt(6)
    for h in ("Heading 1", "Heading 2"):
        doc.styles[h].font.color.rgb = RGBColor(0x1F, 0x3B, 0x73)
    return doc


def title(doc, text, subtitle):
    p = doc.add_heading(text, level=0)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    s = doc.add_paragraph(subtitle)
    s.alignment = WD_ALIGN_PARAGRAPH.CENTER
    s.runs[0].italic = True


def h1(doc, t):
    doc.add_heading(t, level=1)


def h2(doc, t):
    doc.add_heading(t, level=2)


def p(doc, t, bold=False):
    par = doc.add_paragraph()
    run = par.add_run(t)
    run.bold = bold
    return par


def warn(doc, t):
    par = doc.add_paragraph()
    r = par.add_run("Важно: ")
    r.bold = True
    r.font.color.rgb = RGBColor(0xB0, 0x30, 0x30)
    par.add_run(t)


def tip(doc, t):
    par = doc.add_paragraph()
    r = par.add_run("Подсказка: ")
    r.bold = True
    r.font.color.rgb = RGBColor(0x2E, 0x7D, 0x32)
    par.add_run(t)


def steps(doc, items):
    for i, it in enumerate(items, 1):
        doc.add_paragraph(f"{i}. {it}", style="List Number")


def bullets(doc, items):
    for it in items:
        doc.add_paragraph(it, style="List Bullet")


